"""Small-sample estimation on a synthetic cohort, and the event-size table.

    python analyses/analyze.py          # needs pandas, numpy, matplotlib

Reads analyses/results/*.csv (written by make_cohort.ts) and writes results/summary.md
plus two charts. Everything here is SYNTHETIC: the "truth" column exists only because the
players were generated. The point is to check a method, not to report a finding about users.

Question: a player's loss-cut rate is estimated from a handful of rounds. How wrong is the
raw rate k/n, and does pulling it towards the cohort mean, (k + K0*m) / (n + K0), help?
The product uses a correction of this form with K0 = 4 for its style rating (ADR-005 and
server/holdem/phong_cach.ts); this script uses the same form on a different quantity.
"""
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd


def md_table(frame: pd.DataFrame, index: bool = True) -> str:
    f = frame.reset_index() if index else frame
    head = "| " + " | ".join(str(c) for c in f.columns) + " |"
    rule = "|" + "---|" * len(f.columns)
    rows = ["| " + " | ".join("NULL" if pd.isna(v) else str(v) for v in r) + " |" for r in f.itertuples(index=False)]
    return chr(10).join([head, rule, *rows])


R = Path(__file__).parent / "results"
counts = pd.read_csv(R / "02_player_action_counts.csv")
truth = pd.read_csv(R / "truth.csv")
size = pd.read_csv(R / "01_event_size_by_action_type.csv")
mix = pd.read_csv(R / "03_action_mix.csv")

df = counts.merge(truth, on="handle")
df = df[df.n_rounds > 0].copy()
m = df.n_cut_loss.sum() / df.n_rounds.sum()          # pooled cohort mean


def est(k0: float) -> pd.Series:
    return (df.n_cut_loss + k0 * m) / (df.n_rounds + k0)


def rmse(e: pd.Series, mask=None) -> float:
    d = (e - df.true_cut_loss_rate) if mask is None else (e - df.true_cut_loss_rate)[mask]
    return float(np.sqrt((d ** 2).mean()))


# 1) error by sample size: raw vs K0 = 4
bins = [0, 12, 24, 48, 10_000]
labels = ["<=12 rounds", "13-24", "25-48", ">48"]
df["bin"] = pd.cut(df.n_rounds, bins=bins, labels=labels)
raw, k4 = est(0), est(4)
by_bin = pd.DataFrame({
    "players": df.groupby("bin", observed=True).size(),
    "rmse_raw": [rmse(raw, df.bin == b) for b in labels if (df.bin == b).any()],
    "rmse_K0_4": [rmse(k4, df.bin == b) for b in labels if (df.bin == b).any()],
})
by_bin["reduction_pct"] = (100 * (1 - by_bin.rmse_K0_4 / by_bin.rmse_raw)).round(1)

# 2) sweep over K0, whole cohort
sweep = pd.DataFrame({"K0": [0, 1, 2, 4, 8, 16, 32],
                      "rmse": [rmse(est(k)) for k in [0, 1, 2, 4, 8, 16, 32]]})
best = sweep.loc[sweep.rmse.idxmin()]
flat = 100 * (sweep[sweep.K0.between(2, 8)].rmse.max() / best.rmse - 1)

fig, ax = plt.subplots(figsize=(6.4, 3.6), dpi=150)
x = np.arange(len(by_bin)); w = 0.38
ax.bar(x - w / 2, by_bin.rmse_raw, w, label="raw rate k/n", color="#b0450f")
ax.bar(x + w / 2, by_bin.rmse_K0_4, w, label="shrunk, K0 = 4", color="#2f6fde")
ax.set_xticks(x, [f"{i}\n(n={n})" for i, n in zip(by_bin.index, by_bin.players)])
ax.set_ylabel("RMSE vs true rate"); ax.set_title("Synthetic cohort: error by rounds observed", fontsize=10)
ax.legend(frameon=False); ax.spines[["top", "right"]].set_visible(False)
fig.tight_layout(); fig.savefig(R / "error_by_sample_size.png"); plt.close(fig)

fig, ax = plt.subplots(figsize=(6.4, 3.6), dpi=150)
s = size.dropna(subset=["max_bytes"]).sort_values("max_bytes")
ax.barh(s.action_type, s.p50_bytes, color="#2f6fde", label="p50")
ax.barh(s.action_type, s.max_bytes - s.p50_bytes, left=s.p50_bytes, color="#9db8ef", label="up to max")
ax.set_xlabel("snapshot size (bytes, UTF-8)"); ax.set_title("State snapshot size by action type", fontsize=10)
ax.legend(frameon=False); ax.spines[["top", "right"]].set_visible(False)
fig.tight_layout(); fig.savefig(R / "snapshot_size_by_action_type.png"); plt.close(fig)

md = f"""# Results (synthetic cohort)

Generated by `analyses/make_cohort.ts` and `analyses/analyze.py`.
**All numbers below come from {len(df)} generated players. They describe the method, not users.**

Pooled cohort mean cut-loss rate: {m:.3f} · rounds per player: median {int(df.n_rounds.median())}, range {int(df.n_rounds.min())}-{int(df.n_rounds.max())}.

## 1. Error of a player's rate by number of rounds observed

{md_table(by_bin.round(4))}

![error by sample size](error_by_sample_size.png)

## 2. Choice of K0 (whole cohort)

{md_table(sweep.round(4), index=False)}

Lowest RMSE at K0 = {int(best.K0)}, and the curve is flat between K0 = 2 and 8 (RMSE within {flat:.0f} % of the minimum). The cohort's true rates were drawn from Beta(2, 6), whose ideal pseudo-count is 2 + 6 = 8, so a different draw could favour 8: one cohort of {len(df)} players cannot separate the two. The product's K0 = 4 came from a separate 600-match sweep on its own metric; this table does not replace that.

Note the first row of table 1: only {int(by_bin.players.iloc[0])} players have 12 rounds or fewer, so its large reduction rests on very few people.

## 3. Round actions in the cohort

{md_table(mix, index=False)}

## 4. State snapshot size by action type

{md_table(size.round(1), index=False)}

`n_no_snapshot` counts events of that type that store no snapshot (`NULL`). They are not counted as 0 bytes.

![snapshot size](snapshot_size_by_action_type.png)
"""
(R / "summary.md").write_text(md, encoding="utf-8")
print(md)
